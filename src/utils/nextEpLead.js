// ── מתי להציג את "המשך לפרק הבא" ────────────────────────────────────────────
//
// עד כה: 300 שניות קבועות — חמש דקות לפני הסוף. זה מוקדם מדי בעליל. בפרק
// של 25 דקות חמש דקות הן 20% מהפרק: הכרטיס עולה כשהעלילה עוד באמצע, ומסתיר
// חלק מהתמונה לאורך כל השליש האחרון.
//
// מה אורך קרדיטי הסיום בפועל: רצף קרדיטים טיפוסי נע בין 15 שניות לדקה
// (thestreamable, 2017). נטפליקס עצמה לא מפרסמת את אורך סמן "דלג על
// הקרדיטים", אבל ההשהיה לפני ניגון אוטומטי של הפרק הבא אצלה היא 15 שניות
// (הבלוג שלהם). כלומר החלון האמיתי שבו הכרטיס רלוונטי הוא בסדר גודל של
// דקה–שתיים, לא חמש.
//
// אין לנו סמני פרקים בקטלוג (אין chapters/markers בתוכן), ולכן אי אפשר
// לזהות את תחילת הקרדיטים באמת. מה שכן נכון: קרדיטים הם אורך כמעט קבוע,
// ולכן בפרק קצר הם אחוז גדול יותר מהפרק. לכן לא אחוז בלבד ולא מספר קבוע
// בלבד, אלא אחוז עם רצפה ותקרה:
//
//   פרק 25 דקות → 90 שניות    (1.5 דקות, הרצפה)
//   פרק 45 דקות → 135 שניות   (2.25 דקות)
//   פרק 60 דקות ומעלה → 165 שניות (2.75 דקות, התקרה)
//
// הרצפה מגנה על פרקים קצרים (בלעדיה פרק של 20 דקות היה מקבל 60 שניות,
// ואז הכרטיס עולה אחרי שהקרדיטים כבר התחילו), והתקרה מגנה על סרטי-אורך
// (בלעדיה פרק של שעתיים היה מקבל שש דקות — בדיוק התקלה שתוקנה כאן).
//
// זה חל על סדרות בלבד: הכרטיס נגזר מ-hasNext, שקיים רק כשיש פרק הבא.
export const NEXT_EP_MIN_LEAD = 90;
export const NEXT_EP_MAX_LEAD = 165;
export const NEXT_EP_LEAD_RATIO = 0.05;

export function nextEpLead(duration) {
  const d = Number(duration);
  if (!Number.isFinite(d) || d <= 0) return NEXT_EP_MIN_LEAD;
  return Math.min(
    NEXT_EP_MAX_LEAD,
    Math.max(NEXT_EP_MIN_LEAD, Math.round(d * NEXT_EP_LEAD_RATIO)),
  );
}

export default nextEpLead;
