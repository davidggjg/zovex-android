// ── מקור אמת יחיד ל"האם זו טלוויזיה" ────────────────────────────────────────
//
// עד כה ‎Platform.isTV‎ נקרא בתשעה מקומות שונים. זה עבד, אבל זה גם אמר
// שאי אפשר לבדוק את מסלול הטלוויזיה בלי טלוויזיה — וכל תיקון לשלט היה
// עובר דרך בנייה, התקנה על מכשיר, ובדיקה בעיניים.
//
// עכשיו יש גם מצב בדיקה: דגל שנשמר בצד הנייטיב ונקרא **סינכרונית**
// כקבוע של המודול. הסינכרוניות היא העיקר — ‎StyleSheet.create‎, מספר
// העמודות, גובה הבאנר והמקדם כולם מחושבים בזמן טעינת המודולים, ודגל
// שנקרא אחרי זה (AsyncStorage, state) לא היה משנה מהם דבר. לכן גם
// הפעלה מחדש היא חלק מהמנגנון ולא פשרה.
//
// ‎IS_REAL_TV‎ נשאר למקרים שבהם מדובר בחומרה עצמה ולא בפריסה: מכשיר
// בלי מסך מגע, WebView חלש, היעדר PiP. אסור לזייף אותם על טלפון.

import {Platform, NativeModules} from 'react-native';

const DEV_TV = (() => {
  try {
    return NativeModules.DevTv?.getConstants?.().tvEmulation === true;
  } catch (_) {
    return false;
  }
})();

/** טלוויזיה אמיתית — חומרה. */
export const IS_REAL_TV = Platform.isTV;

/** האם להתנהג כטלוויזיה: פריסה, פוקוס, שלט. */
export const IS_TV = Platform.isTV || DEV_TV;

/** האם אנחנו במצב הבדיקה (טלפון שמתנהג כטלוויזיה). */
export const IS_TV_EMULATED = !Platform.isTV && DEV_TV;

export default IS_TV;
