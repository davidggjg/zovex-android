// ── מערכת העיצוב של ZOVEX — מקור אמת יחיד ל-tokens ─────────────────────────
//
// נבנה מתוך design/DESIGN_SYSTEM_HE.md. המסכים מאמצים אותו בהדרגה; עד
// שמסך מאמץ, הצבעים הקשיחים הקיימים נשארים כפי שהם. אין החלפה גורפת —
// המפרט עצמו מזהיר לבדוק ניגודיות וקריאות לכל מעבר.
//
// למה קובץ אחד ולא theme context: אין כאן החלפת ערכת נושא בזמן ריצה
// (ZOVEX הוא כהה בלבד), ולכן אובייקט קבוע הוא הפשוט והזול ביותר — בלי
// provider, בלי re-render, נקרא ישירות ב-StyleSheet.create בכל מסך.

import {Platform} from 'react-native';

export const IS_TV = Platform.isTV;

// ── צבעים ────────────────────────────────────────────────────────────────
export const colors = {
  bg: '#08090D',            // רקע עמוק
  surface: '#111319',       // משטח
  surfaceElevated: '#191C24', // משטח מורם (מודאל, כרטיס פעיל)
  primary: '#E50924',       // אדום המותג — ממוקד, לא על כל רכיב
  primaryHi: '#FF3348',     // הדגשת אדום (focus/hover)
  text: '#F7F7F9',          // טקסט ראשי
  textSecondary: '#A6A9B3', // טקסט משני
  textMuted: '#737783',     // טקסט מעומעם
  border: '#292D37',        // גבול דק
  success: '#3CBF8A',
  warning: '#F2B84B',

  // שקיפויות נפוצות, מוגדרות פעם אחת כדי שלא יתפזרו ערכים שונים
  overlay: 'rgba(0,0,0,0.65)',       // באדג' על תמונה
  scrim: 'rgba(8,9,13,0.92)',        // רקע מודאל
  focusTint: 'rgba(229,9,36,0.18)',  // מילוי עדין למצב פעיל
  hairline: 'rgba(255,255,255,0.10)',// כפתור משני
};

// ── מרווחים ─────────────────────────────────────────────────────────────
// בסיס: 4, 8, 12, 16, 20, 24, 32. גישה דרך space(n) או דרך השמות.
export const spacing = {
  xs: 4, sm: 8, md: 12, lg: 16, xl: 20, xxl: 24, xxxl: 32,
};
export const space = n => spacing[n] ?? n;

// ── רדיוסים ─────────────────────────────────────────────────────────────
export const radius = {
  card: 14,     // כרטיסים: 10–16
  button: 12,   // כפתורים ראשיים: 10–14
  pill: 999,
  sm: 8,
};

// ── טיפוגרפיה ───────────────────────────────────────────────────────────
// טקסט בטלוויזיה גדול יותר ונקרא ממרחק. tv(phone, tv) בוחר לפי הפלטפורמה,
// כך שאותו token נותן גודל נכון בשני העולמות בלי תנאים בכל מסך.
const tv = (phone, tvSize) => (IS_TV ? tvSize : phone);
export const font = {
  hero: tv(32, 44),       // כותרת ראשית
  screenTitle: tv(26, 34),
  section: tv(19, 26),    // כותרת שורה/מקטע
  cardTitle: tv(15, 19),
  body: tv(14, 18),
  label: tv(13, 16),
  caption: tv(12, 15),    // לא קטן מדי, גם בטלפון
  weightBold: '800',
  weightMed: '600',
};

// ── תנועה ───────────────────────────────────────────────────────────────
// אנימציות קצרות וממוקדות; לא להפעיל בכל כרטיס בזמן גלילה.
export const motion = {
  fast: 120,
  base: 180,
  slow: 220,
};

// ── צללים/עומק ──────────────────────────────────────────────────────────
// עומק בשכבות ובצל עדין, לא במסגרות. elevation לאנדרואיד; הצל המפורש
// לטלפון בלבד — בטלוויזיה הוא עולה בביצועים על עשרות כרטיסים ולא נראה.
export const elevation = depth => (IS_TV ? {} : {
  shadowColor: '#000',
  shadowOpacity: 0.35,
  shadowRadius: depth * 2,
  shadowOffset: {width: 0, height: depth},
  elevation: depth,
});

export default {colors, spacing, space, radius, font, motion, elevation, IS_TV};
