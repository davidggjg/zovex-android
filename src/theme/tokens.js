// (ZOVEX הוא כהה בלבד), ולכן אובייקט קבוע הוא הפשוט והזול ביותר — בלי
// provider, בלי re-render, נקרא ישירות ב-StyleSheet.create בכל מסך.

import {Platform} from 'react-native';

export const IS_TV = Platform.isTV;

// ── צבעים ────────────────────────────────────────────────────────────────
