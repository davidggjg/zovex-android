  primaryHi: '#FF3348',     // הדגשת אדום (focus/hover)
  text: '#F7F7F9',          // טקסט ראשי
  textSecondary: '#A6A9B3', // טקסט משני
  textMuted: '#737783',     // טקסט מעומעם
  border: '#292D37',        // גבול דק
  success: '#3CBF8A',
  warning: '#F2B84B',

  // שקיפויות נפוצות, מוגדרות פעם אחת כדי שלא יתפזרו ערכים שונים
  overlay: 'rgba(0,0,0,0.65)',       // באדג' על תמונה
  scrim: 'rgba(8,9,13,0.92)',        // רקע מודאל
  focusTint: 'rgba(229,9,36,0.18)',  // מילוי עדין למצב פעיל
  hairline: 'rgba(255,255,255,0.10)',// כפתור משני

  // ── שפה עתידנית: זכוכית וזוהר ───────────────────────────────────────
